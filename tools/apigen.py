#!/usr/bin/env python3
"""Generate the Vehicle API v1 key tables from api/vehicle_api.yaml (the only hand-written copy of the keys).

  apps/node/src/vehicle_api.h   C: VAPI_<NAME> key strings, type/QoS/max-age table, legacy aliases
  tools/vehicle_api.py          Python: KEYS dict + helpers (console, bridges, sidecar)
  docs/VEHICLE_API_KEYS.md      the table for people (and for whoever writes the documents)
    tools/apigen.py [--check]   (--check: fail if a generated file is out of date)
"""
import hashlib
import os
import re
import sys

import yaml

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
SRC = os.path.join(ROOT, 'api', 'vehicle_api.yaml')
raw = open(SRC, 'rb').read()
api = yaml.safe_load(raw)
HASH = hashlib.sha256(raw).hexdigest()[:8]  # carried in ecu/<ecu>/status, so a node on another table shows
TYPES = {'bool', 'u8', 'i8', 'u16', 'i16', 'f32', 'json', 'bytes'}
QOS = {'realtime': 0, 'interactive': 1, 'data': 2, 'background': 3}

keys = api['keys']
seen = set()
for k in keys:
    assert k['type'] in TYPES, k
    assert k['qos'] in QOS, k
    assert k['key'] not in seen, f"duplicate {k['key']}"
    seen.add(k['key'])
    k.setdefault('unit', '')
    k.setdefault('target', False)
    k.setdefault('vss', '')
    k.setdefault('legacy', [])


def cname(key):
    s = key.replace('vehicle/', '', 1).replace('ecu/{ecu}/', 'ecu/')
    for a, b in (('body/lights/', 'LIGHT_'), ('directionindicator/', 'TURN_'), ('obstacledetection/', 'OBST_'),
                 ('powertrain/transmission/', ''), ('chassis/', ''), ('private/', 'P_')):
        s = s.replace(a, b)
    return 'VAPI_' + re.sub(r'[^A-Za-z0-9]+', '_', s).strip('_').upper()


def cfmt(key):  # "{ecu}" -> "%s", "{id}" -> "%u" for snprintf
    return key.replace('{ecu}', '%s').replace('{id}', '%u')


GEN = f'generated by tools/apigen.py from api/vehicle_api.yaml (v{api["version"]}, VSS {api["vss"]}, #{HASH}) -- do not edit'

# ---------------------------------------------------------------- C
c = [f'/* {GEN} */', '#pragma once', '#include <stdint.h>', '',
     f'#define VAPI_VERSION {api["version"]}', f'#define VAPI_HASH "{HASH}"', f'#define VAPI_VSS "{api["vss"]}"', '',
     'enum vapi_type { ' + ', '.join(f'VAPI_T_{t.upper()}' for t in sorted(TYPES)) + ' };',
     'enum vapi_qos { ' + ', '.join(f'VAPI_Q_{q.upper()} = {v}' for q, v in QOS.items()) + ' };', '']
for k in keys:
    n = cname(k['key'])
    c.append(f'#define {n} "{cfmt(k["key"])}"')
    if k['target']:
        c.append(f'#define {n}_TARGET "{cfmt(k["key"])}/target"')
    for i, l in enumerate(k['legacy']):
        c.append(f'#define {n}_OLD{i if i else ""} "{cfmt(l)}" /* legacy, until migration step 5 */')
c += ['', 'struct vapi_key { const char *key; uint8_t type, qos, target; uint16_t max_age_ms; };',
      'static const struct vapi_key vapi_keys[] = {']
for k in keys:
    c.append(f'\t{{{cname(k["key"])}, VAPI_T_{k["type"].upper()}, VAPI_Q_{k["qos"].upper()}, '
             f'{int(k["target"])}, {k["max_age"]}}},')
c += ['};', f'#define VAPI_NKEYS {len(keys)}', '']

# ---------------------------------------------------------------- Python
p = [f'"""{GEN}"""', f'VERSION = {api["version"]}', f'HASH = {HASH!r}', f'VSS = {api["vss"]!r}', '', 'KEYS = {']
for k in keys:
    d = {f: k[f] for f in ('type', 'unit', 'owner', 'qos', 'max_age', 'target', 'vss', 'legacy')}
    p.append(f'    {k["key"]!r}: {d!r},')
p += ['}', '', 'STRUCT = {"bool": "<B", "u8": "<B", "i8": "<b", "u16": "<H", "i16": "<h", "f32": "<f"}', '',
      '# old key -> v1 key (with {ecu}/{id} left in for the ECU topics)',
      'LEGACY = {old: new for new, d in KEYS.items() for old in d["legacy"]}', '', '',
      'def pack(key, value):',
      '    import json, struct',
      '    t = KEYS[key]["type"]',
      '    if t == "json":',
      '        return json.dumps(value, separators=(",", ":")).encode()',
      '    if t == "bytes":',
      '        return bytes(value)',
      '    return struct.pack(STRUCT[t], int(value) if t != "f32" else float(value))', '', '',
      'def unpack(key, payload):',
      '    import json, struct',
      '    t = KEYS[key]["type"]',
      '    if t == "json":',
      '        return json.loads(payload)',
      '    if t == "bytes":',
      '        return bytes(payload)',
      '    return struct.unpack(STRUCT[t], bytes(payload)[:struct.calcsize(STRUCT[t])])[0]', '']

# ---------------------------------------------------------------- Markdown
m = [f'# Vehicle API v{api["version"]} keys', '', f'_{GEN}. Design: [VEHICLE_API.md](VEHICLE_API.md)._', '',
     '| key | type | unit | owner | QoS | max age ms | `/target` | VSS 6.1 | replaces |', '|---|---|---|---|---|---|---|---|---|']
for k in keys:
    m.append(f'| `{k["key"]}` | {k["type"]} | {k["unit"]} | {k["owner"]} | {k["qos"]} | {k["max_age"] or "event"} | '
             f'{"yes" if k["target"] else ""} | {k["vss"] or "overlay"} | {", ".join(f"`{x}`" for x in k["legacy"])} |')
m.append('')

out = {'apps/node/src/vehicle_api.h': '\n'.join(c), 'tools/vehicle_api.py': '\n'.join(p),
       'docs/VEHICLE_API_KEYS.md': '\n'.join(m)}
stale = []
for f, s in out.items():
    path = os.path.join(ROOT, f)
    old = open(path).read() if os.path.exists(path) else None
    if old != s:
        stale.append(f)
        if '--check' not in sys.argv:
            open(path, 'w').write(s)
print(('stale: ' if '--check' in sys.argv else 'wrote: ') + (', '.join(stale) or 'nothing') + f'  (#{HASH}, {len(keys)} keys)')
sys.exit(1 if stale and '--check' in sys.argv else 0)
